#!/usr/bin/env node
/**
 * Construit la vue MCP App de la Session Card et l'écrit comme constante TypeScript
 * committée (`supabase/functions/mcp/resources/views/sessionCard.generated.ts`).
 *
 * Le document est auto-suffisant : le markup est pré-rendu (repli sans JS), le CSS inline
 * vient des valeurs de tokens et des utilitaires compilés de `@nomosui/react/view.css`
 * (ADR 0034). Rejouer : `npm run build:view` ; vérifier la dérive : `npm run view:check`.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import { build } from 'esbuild'

const require = createRequire(import.meta.url)
const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..')
const TMP = path.join(ROOT, '.view-build')
const TARGET = path.join(ROOT, 'supabase/functions/mcp/resources/views/sessionCard.generated.ts')

const TOKENS_CSS = readFileSync(require.resolve('@nomosui/react/tokens/tokens.generated.css'), 'utf8')
const VIEW_CSS = readFileSync(require.resolve('@nomosui/react/view.css'), 'utf8')

async function renderExample() {
  mkdirSync(TMP, { recursive: true })
  const outfile = path.join(TMP, 'render.mjs')
  await build({
    entryPoints: [path.join(ROOT, 'src/mcp-views/session-card/render.tsx')],
    bundle: true,
    format: 'esm',
    platform: 'node',
    packages: 'external',
    jsx: 'automatic',
    outfile,
    logLevel: 'silent',
  })
  const mod = await import(pathToFileURL(outfile).href)
  return mod.renderExampleSessionCard()
}

const markup = await renderExample()
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<style>${TOKENS_CSS}
${VIEW_CSS}</style>
</head>
<body>
<div id="gl-view-root">${markup}</div>
</body>
</html>
`

const header =
  '/**\n * Generated by scripts/build-mcp-view.mjs — do not edit by hand.\n * Replay: npm run build:view\n */\n'
const next = `${header}export const SESSION_CARD_HTML = ${JSON.stringify(html)}\n`

rmSync(TMP, { recursive: true, force: true })

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(TARGET, 'utf8')
  } catch {
    current = ''
  }
  if (current !== next) {
    console.error('sessionCard.generated.ts is stale: replay `npm run build:view`.')
    process.exit(1)
  }
  console.log('sessionCard.generated.ts is up to date.')
} else {
  mkdirSync(path.dirname(TARGET), { recursive: true })
  writeFileSync(TARGET, next)
  console.log(`wrote ${path.relative(ROOT, TARGET)}`)
}
