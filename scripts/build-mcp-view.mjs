#!/usr/bin/env node
/**
 * Construit les vues MCP App et les écrit comme constantes TypeScript committées
 * (`supabase/functions/mcp/resources/views/*.generated.ts`).
 *
 * Chaque document est auto-suffisant : le markup est pré-rendu (repli sans JS), le CSS
 * inline vient des valeurs de tokens et des utilitaires compilés de `@nomosui/react/view.css`
 * (ADR 0034). Rejouer : `npm run build:view` ; vérifier la dérive : `npm run view:check`.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

import { build } from 'esbuild'
import { build as viteBuild } from 'vite'

const require = createRequire(import.meta.url)
const HERE = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(HERE, '..')
const TMP = path.join(ROOT, '.view-build')

const TOKENS_CSS = readFileSync(path.join(ROOT, 'src/styles/glSkin.generated.css'), 'utf8')
const VIEW_CSS = readFileSync(require.resolve('@nomosui/react/view.css'), 'utf8')

const VIEWS = [
  {
    label: 'session-card',
    entry: 'src/mcp-views/session-card/entry.tsx',
    render: 'src/mcp-views/session-card/render.tsx',
    renderFn: 'renderExampleSessionCard',
    bundleName: 'GymLogicSessionCardView',
    constName: 'SESSION_CARD_HTML',
    target: 'supabase/functions/mcp/resources/views/sessionCard.generated.ts',
  },
  {
    label: 'program-patch',
    entry: 'src/mcp-views/program-patch/entry.tsx',
    render: 'src/mcp-views/program-patch/render.tsx',
    renderFn: 'renderExampleProgramPatch',
    bundleName: 'GymLogicProgramPatchView',
    constName: 'PROGRAM_PATCH_HTML',
    target: 'supabase/functions/mcp/resources/views/programPatch.generated.ts',
  },
]

async function renderExample(view) {
  mkdirSync(TMP, { recursive: true })
  const outfile = path.join(TMP, `render-${view.label}.mjs`)
  await build({
    entryPoints: [path.join(ROOT, view.render)],
    bundle: true,
    format: 'esm',
    platform: 'node',
    packages: 'external',
    jsx: 'automatic',
    outfile,
    logLevel: 'silent',
  })
  const mod = await import(pathToFileURL(outfile).href)
  return mod[view.renderFn]()
}

async function bundleClient(view) {
  const outDir = path.join(TMP, `client-${view.label}`)
  await viteBuild({
    configFile: false,
    root: ROOT,
    logLevel: 'silent',
    define: { 'process.env.NODE_ENV': '"production"' },
    esbuild: { jsx: 'automatic' },
    build: {
      outDir,
      emptyOutDir: true,
      minify: true,
      lib: {
        entry: path.join(ROOT, view.entry),
        formats: ['iife'],
        name: view.bundleName,
        fileName: () => 'view.js',
      },
      rollupOptions: { output: { inlineDynamicImports: true } },
    },
  })
  return readFileSync(path.join(outDir, 'view.js'), 'utf8')
}

async function buildHtml(view) {
  const markup = await renderExample(view)
  const clientJs = (await bundleClient(view)).replaceAll('</script', '<\\/script')
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<style>${TOKENS_CSS}
${VIEW_CSS}</style>
</head>
<body>
<div id="gl-view-root">${markup}</div>
<script>${clientJs}</script>
</body>
</html>
`
}

const header =
  '/**\n * Generated by scripts/build-mcp-view.mjs — do not edit by hand.\n * Replay: npm run build:view\n */\n'

const check = process.argv.includes('--check')
let stale = false

for (const view of VIEWS) {
  const html = await buildHtml(view)
  const next = `${header}export const ${view.constName} = ${JSON.stringify(html)}\n`
  const target = path.join(ROOT, view.target)

  if (check) {
    let current = ''
    try {
      current = readFileSync(target, 'utf8')
    } catch {
      current = ''
    }
    if (current !== next) {
      console.error(`${view.target} is stale: replay \`npm run build:view\`.`)
      stale = true
    }
  } else {
    mkdirSync(path.dirname(target), { recursive: true })
    writeFileSync(target, next)
    console.log(`wrote ${path.relative(ROOT, target)}`)
  }
}

rmSync(TMP, { recursive: true, force: true })

if (check) {
  if (stale) process.exit(1)
  console.log('MCP view artifacts are up to date.')
}
